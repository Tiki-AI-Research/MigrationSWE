#!/usr/bin/env python3
"""Check baseline-refresh orchestration without running candidate code."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile
import unittest
from unittest.mock import patch

import refresh_baseline
import verifier
from test_integrity import evaluate_test_integrity
from verifier import _load_baseline_evidence


TESTS = Path(__file__).resolve().parent.parent
REAL_RUN = subprocess.run


class BaselineRefreshTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="sharing-baseline-selftest-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.tests = self.root / "tests"
        for name in (
            "config.json", "verifier/test.patch", "verifier/fixtures/sha256.json",
            "verifier/fixtures/official_reference.patch", "assets/baseline-node-results.json",
            "assets/assets-manifest.json",
        ):
            target = self.tests / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(TESTS / name, target)
        self.config = json.loads((self.tests / "config.json").read_text())
        self.config["baseline_evidence"] = str(self.tests / "assets/baseline-node-results.json")
        (self.tests / "config.json").write_text(json.dumps(self.config))
        self.node_ids = [
            *self.config["f2p"], *self.config["hard_gate_behavior"]["p2p"],
            *self.config["hard_gate_behavior"]["differential"],
        ]
        self.set_matching_baseline_fixture()
        self.base = self.root / "base"
        self.base.mkdir()
        with tarfile.open(TESTS / "assets/base-repo.tar.gz", "r:gz") as archive:
            archive.extractall(self.base)
        (self.base / "node_modules").mkdir()
        self.argv = [
            "refresh_baseline.py", "--if-stale", "--tests-root", str(self.tests),
            "--solution-patch", str(self.tests / "verifier/fixtures/official_reference.patch"),
            "--base-repo", str(self.base), "--work-root", str(self.root / "work"),
        ]

    def set_matching_baseline_fixture(self):
        # Synthetic evidence for this unit test's temporary directory only.
        # Do not relabel real historical measurements as current. Derive the
        # fixture's complete identity and node inventory from today's suite.
        baseline = {
            "schema_version": "harbor-migration-baseline/v1",
            **{key: self.config[key] for key in ("task_id", "base_commit", "base_tree_hash", "test_patch_sha256")},
            "gold_patch_sha256": hashlib.sha256(
                (self.tests / "verifier/fixtures/official_reference.patch").read_bytes()
            ).hexdigest(),
            "evidence": {},
        }
        cases = verifier._differential_case_ids(self.tests)
        for node_id in self.node_ids:
            group, stem = node_id.split("::", 1)
            result_ids = cases if group == "differential" else [stem]
            script = f"suite/{group}/{'behavior-oracle' if group == 'differential' else stem}.js"
            item = {}
            for side in ("base", "gold"):
                passed = not (side == "base" and group == "f2p")
                item.update({
                    f"{side}_status": "passed" if passed else "failed_as_expected",
                    f"{side}_passed": len(result_ids) if passed else 0,
                    f"{side}_total": len(result_ids),
                    f"{side}_exit_code": 0 if passed else 1,
                    f"{side}_command": ["node", script],
                    f"{side}_results": [{"id": case_id, "pass": passed} for case_id in result_ids],
                })
            baseline["evidence"][node_id] = item
        (self.tests / "assets/baseline-node-results.json").write_text(json.dumps(baseline))

    def set_baseline_patch_hash(self, digest):
        path = self.tests / "assets/baseline-node-results.json"
        data = json.loads(path.read_text())
        data["test_patch_sha256"] = digest
        path.write_text(json.dumps(data))

    def set_baseline_gold_hash(self, digest):
        # Only update this test's temporary fixture. Real baseline evidence
        # must still be regenerated by measuring the base and gold versions.
        path = self.tests / "assets/baseline-node-results.json"
        data = json.loads(path.read_text())
        data["gold_patch_sha256"] = digest
        path.write_text(json.dumps(data))

    def assets(self):
        return tuple((self.tests / name).read_bytes() for name in (
            "assets/baseline-node-results.json", "assets/assets-manifest.json",
        ))

    def test_matching_baseline_is_not_remeasured(self):
        self.assert_matching_baseline_is_not_remeasured()

    def test_distributed_reference_patches_include_required_tests(self):
        # Rebuild from the actual distributed patches, not an existing checkout
        # that may contain an untracked smoke test omitted from the patch.
        sources = [
            TESTS / "verifier/fixtures/official_reference.patch",
            TESTS / "verifier/fixtures/allowed_test_patch_control.patch",
        ]
        solution = TESTS.parent / "solution/solution.patch"
        if solution.is_file():  # The solution is not shipped in the evaluator image.
            sources.append(solution)
        for source in sources:
            with self.subTest(patch=source):
                gold = self.root / source.stem
                shutil.copytree(self.base, gold)
                REAL_RUN(["git", "apply", "--binary", str(source)], cwd=gold, check=True)
                result = evaluate_test_integrity(gold, base_dir=self.base)
                self.assertTrue(result["success"], result)

    def test_incomplete_reference_stops_before_install_or_measurement(self):
        reference = self.tests / "verifier/fixtures/official_reference.patch"
        sections = reference.read_text().split("diff --git ")
        reference.write_text("diff --git ".join(
            section for section in sections
            if not section.startswith("a/test/fastify-smoke.js ")
        ))
        hashes_path = self.tests / "verifier/fixtures/sha256.json"
        hashes = json.loads(hashes_path.read_text())
        hashes["official_reference.patch"] = hashlib.sha256(reference.read_bytes()).hexdigest()
        hashes_path.write_text(json.dumps(hashes))
        before = self.assets()

        with patch.object(sys, "argv", self.argv), \
                patch.object(refresh_baseline, "measured_side") as measure, \
                patch.object(refresh_baseline.subprocess, "run", wraps=REAL_RUN) as run:
            with self.assertRaisesRegex(RuntimeError, "reference test contract failed"):
                refresh_baseline.main()
        measure.assert_not_called()
        self.assertFalse(any(call.args[0][0] == "npm" for call in run.call_args_list))
        self.assertEqual(before, self.assets())

    def test_matching_fixture_tracks_added_removed_and_reordered_differential_cases(self):
        cases = verifier._differential_case_ids(self.tests)
        for changed in (cases + ["C9999"], cases[:1], list(reversed(cases))):
            with self.subTest(cases=changed), patch.object(verifier, "_differential_case_ids", return_value=changed):
                self.set_matching_baseline_fixture()
                self.assert_matching_baseline_is_not_remeasured()

    def test_current_baseline_rejects_mismatched_base_and_gold_case_inventory(self):
        path = self.tests / "assets/baseline-node-results.json"
        for side in ("base", "gold"):
            with self.subTest(side=side):
                self.set_matching_baseline_fixture()
                baseline = json.loads(path.read_text())
                for node_id, item in baseline["evidence"].items():
                    if node_id.startswith("differential::"):
                        item[f"{side}_results"].append({"id": "C9999", "pass": True})
                        item[f"{side}_passed"] += 1
                        item[f"{side}_total"] += 1
                path.write_text(json.dumps(baseline))
                with self.assertRaisesRegex(ValueError, f"baseline {side} differential cases differ"):
                    _load_baseline_evidence(self.config, self.tests, self.node_ids)

    def assert_matching_baseline_is_not_remeasured(self):
        evidence = _load_baseline_evidence(self.config, self.tests, self.node_ids)
        self.assertTrue(all(item["provenance"] == "current" for item in evidence.values()))
        before = self.assets()
        with patch.object(sys, "argv", self.argv), \
                patch.object(refresh_baseline, "measured_side") as measure, \
                patch.object(refresh_baseline.subprocess, "run") as run:
            self.assertEqual(refresh_baseline.main(), 0)
        measure.assert_not_called()
        run.assert_not_called()
        self.assertEqual(before, self.assets())

    def test_stale_baseline_is_rebuilt_only_after_all_sides_succeed(self):
        self.set_baseline_patch_hash("0" * 64)
        self.assert_stale_baseline_is_rebuilt()

    def test_changed_reference_is_remeasured_even_when_test_patch_matches(self):
        self.set_baseline_patch_hash(self.config["test_patch_sha256"])
        self.set_baseline_gold_hash("0" * 64)
        self.assert_stale_baseline_is_rebuilt()

    def assert_stale_baseline_is_rebuilt(self):
        evidence = _load_baseline_evidence(self.config, self.tests, self.node_ids)
        self.assertTrue(all(item["provenance"] == "stale" for item in evidence.values()))

        def measured(workspace, node_id, repo, base):
            failed = repo == base and node_id.startswith("f2p::")
            _, display = refresh_baseline.script_for(workspace, node_id)
            return {
                "status": "candidate_failure" if failed else "passed",
                "exit_code": 1 if failed else 0, "command": ["node", display],
            }

        def run(command, **kwargs):
            if command[0] == "npm":
                return subprocess.CompletedProcess(command, 0)
            return REAL_RUN(command, **kwargs)

        with patch.object(sys, "argv", self.argv), \
                patch.object(refresh_baseline, "measured_side", side_effect=measured) as measure, \
                patch.object(refresh_baseline.subprocess, "run", side_effect=run):
            self.assertEqual(refresh_baseline.main(), 0)
        self.assertEqual(measure.call_count, len(self.node_ids) * 2)
        evidence = _load_baseline_evidence(self.config, self.tests, self.node_ids)
        self.assertTrue(all(item["provenance"] == "current" for item in evidence.values()))
        baseline_bytes, manifest_bytes = self.assets()
        manifest = json.loads(manifest_bytes)
        self.assertEqual(manifest["assets"]["baseline_node_results"]["sha256"],
                         hashlib.sha256(baseline_bytes).hexdigest())

    def test_measurement_failure_preserves_historical_assets(self):
        self.set_baseline_patch_hash("0" * 64)
        before = self.assets()

        def run(command, **kwargs):
            if command[0] == "npm":
                return subprocess.CompletedProcess(command, 0)
            return REAL_RUN(command, **kwargs)

        with patch.object(sys, "argv", self.argv), \
                patch.object(refresh_baseline, "measured_side", side_effect=RuntimeError("measurement failed")), \
                patch.object(refresh_baseline.subprocess, "run", side_effect=run):
            with self.assertRaisesRegex(RuntimeError, "measurement failed"):
                refresh_baseline.main()
        self.assertEqual(before, self.assets())


if __name__ == "__main__":
    unittest.main()
